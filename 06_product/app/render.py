"""Follow-ups and exports are assembled from templates, with no model-written text, to guarantee nothing is fabricated."""
import csv
import html
import io
import json

T = {"fulfilled": "Reported done in the meeting", "partial_or_rescheduled": "Unfinished or rescheduled", "abandoned": "Dropped", "not_mentioned": "Not mentioned"}
K = {"todo": "To do", "doing": "In progress", "done": "Done", "dropped": "Dropped"}


def owner_text(i) -> str:
    if i["owner_state"] == "given" and i["owner_value"]:
        return i["owner_value"]
    if i["owner_state"] == "vague":
        return f"To be confirmed (quote: {i['owner_value'] or 'unspecified'})"
    return "Unassigned"


def due_text(i) -> str:
    if i["due_date"]:
        return i["due_date"] + (f" (quote: {i['due_raw']})" if i["due_raw"] else "")
    if i["due_raw"]:
        return f"{i['due_raw']} (unclear time)"
    return "TBD"


def followups(items: list[dict], meeting_date: str, limit: int = 7) -> str:
    qs = []
    for i in items:
        if i["review"] in ("rejected", "merged") or i["task_status"] not in ("todo", "doing"):
            continue  # Don't follow up on items already closed or rejected
        q = i["title"] or i["quote"]
        who = i.get("speaker")
        who = f" ({who})" if who else ""
        if i["kind"] == "question":
            qs.append(f"{q}{who}: still undecided. Decide next time?")
        elif i["kind"] != "commitment":
            continue
        elif i["owner_state"] != "given":
            qs.append(f"{q}{who}: no owner yet. Who will take it?")
        elif i["due_state"] == "vague":
            qs.append(f"{q} ({i['owner_value']}): the quote says \"{i['due_raw']}\". Which day exactly?")
    if not qs:
        return ""
    head = f"[To confirm after the meeting · {meeting_date}] (generated by Meeting Ledger; original quotes available)"
    body = [f"{n}. {t}" for n, t in enumerate(qs[:limit], 1)]
    if len(qs) > limit:
        body.append(f"{len(qs) - limit} more not listed.")
    return "\n".join([head, *body, "The above is compiled from the meeting's original quotes. Please correct anything inaccurate."])


def safe(s) -> str:
    """Exported Markdown may get rendered, so all HTML from the meeting is escaped."""
    return html.escape(str(s or ""), quote=False)


def minutes_md(m: dict, utts, items, props, tasks) -> str:
    out = [f"# {safe(m['title']) or 'Meeting'} · {m['date']}", ""]
    # Export only conclusions a person has confirmed; rejected ones are omitted, pending ones are listed separately
    conf_p = [p for p in props if p["decision"] == "confirmed"]
    pend_p = [p for p in props if p["decision"] == "pending"]
    if conf_p or pend_p:
        out += ["## Progress on items from last time", ""]
        for p in conf_p:
            ev = json.loads(p["evidence_json"])
            out.append(f"- **{T[p['transition']]}** · {safe(owner_text(p))}: {safe(p['item_title'] or p['item_quote'])} (\"{safe(ev[0]['quote'])}\")")
        if pend_p:
            out += ["", "To confirm:", ""]
            out += [f"- {T[p['transition']]}? {safe(p['item_title'] or p['item_quote'])}" for p in pend_p]
        out.append("")
    conf = [i for i in items if i["kind"] == "commitment" and i["review"] == "confirmed"]
    by_owner: dict[str, list] = {}
    for i in conf:
        by_owner.setdefault(owner_text(i), []).append(i)
    pend = [i for i in items if i["kind"] == "commitment" and i["review"] == "pending"]
    out += ["## Who committed to what (confirmed)", ""]
    if not conf:
        out.append("- None yet")
    for who, rows in by_owner.items():
        out.append(f"**{safe(who)}**")
        out += [f"- [{'x' if i['task_status'] == 'done' else ' '}] {safe(i['title'] or i['quote'])} — {safe(due_text(i))} (\"{safe(i['quote'])}\")" for i in rows]
    if pend:
        out += ["", "## Task drafts (unconfirmed)", ""] + [f"- {safe(i['title'] or i['quote'])} — {safe(owner_text(i))} — {safe(due_text(i))}" for i in pend]
    for kind, title in (("decision", "Decisions"), ("result", "Results"), ("question", "Open questions")):
        rows = [i for i in items if i["kind"] == kind and i["review"] != "rejected"]
        if rows:
            out += ["", f"## {title}", ""] + [f"- {safe(i['title'] or i['quote'])} (\"{safe(i['quote'])}\")" for i in rows]
    out += ["", "## Transcript", ""]
    out += [(f"[{u['ts']}] " if u["ts"] else "") + (f"{safe(u['speaker'])}: " if u["speaker"] else "") + safe(u["text"]) for u in utts]
    return "\n".join(out) + "\n"


def csv_cell(s) -> str:
    """Guard against CSV formula injection: spreadsheet software executes cells starting with = + - @."""
    s = str(s or "")
    return "'" + s if s[:1] in ("=", "+", "-", "@", "\t", "\r") else s


def tasks_csv(rows) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["title", "owner", "due_date", "due_raw", "status", "source_quote", "meeting_date"])
    for r in rows:
        w.writerow([csv_cell(x) for x in (r["title"] or r["quote"], r["owner_value"] if r["owner_state"] == "given" else "", r["due_date"] or "", r["due_raw"] or "", r["task_status"], r["quote"] or "", r["m_date"] or "")])
    return "\ufeff" + buf.getvalue()
